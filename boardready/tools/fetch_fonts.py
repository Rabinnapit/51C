"""Download open-license fonts from Google Fonts (latin subset) and embed them as base64 @font-face rules
in app/src/css/00-fonts.css so the built app needs zero network access.
Fonts (all SIL Open Font License):
  Instrument Serif  400 normal + italic  -> --font-display
  Manrope           variable 200..800    -> --font-body
  JetBrains Mono    400, 600             -> --font-mono
"""
import re, base64, urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "css" / "00-fonts.css"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36"
FAMILIES = [
    ("Instrument Serif", "family=Instrument+Serif:ital@0;1"),
    ("Manrope", "family=Manrope:wght@200..800"),
    ("JetBrains Mono", "family=JetBrains+Mono:wght@400;600"),
]


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


css_out = ["/* Embedded fonts (SIL OFL). Generated by tools/fetch_fonts.py. Do not edit by hand. */"]
total = 0
for name, q in FAMILIES:
    css = get(f"https://fonts.googleapis.com/css2?{q}&display=swap").decode("utf-8")
    blocks = re.findall(r"/\* (\w+) \*/\s*@font-face \{(.*?)\}", css, flags=re.S)
    for subset, body in blocks:
        if subset != "latin":
            continue
        url = re.search(r"url\((https://[^)]+)\)", body).group(1)
        fmt = re.search(r"format\('(\w+)'\)", body).group(1)
        data = get(url)
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        body2 = re.sub(r"src:\s*url\([^)]+\)\s*format\('\w+'\);", f"src: url(data:font/{fmt};base64,{b64}) format('{fmt}');", body)
        body2 = re.sub(r"unicode-range:[^;]+;", "", body2)
        css_out.append("@font-face {" + body2.strip() + "}")
        print(f"{name}: {subset} {fmt} {len(data)//1024} KB")

OUT.write_text("\n".join(css_out), encoding="utf-8")
print(f"wrote {OUT} ({OUT.stat().st_size//1024} KB css, {total//1024} KB raw font bytes)")
